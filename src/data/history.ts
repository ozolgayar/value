export type HistoryYearEntry = HistoryYear & {
  eraId: string
  eraIndex: number
  globalIndex: number
}

export const historyYears: HistoryYearEntry[] = historyEras.flatMap((era, eraIndex) =>
  era.years.map((y, yearIndexInEra) => ({
    ...y,
    eraId: era.id,
    eraIndex,
    globalIndex:
      historyEras.slice(0, eraIndex).reduce((sum, e) => sum + e.years.length, 0) + yearIndexInEra,
  })),
)

export const HISTORY_PAGE_SIZE = 4
export const historyPageCount = Math.ceil(historyYears.length / HISTORY_PAGE_SIZE)

/** Years shown in the side «piano» navigator — every year that has a timeline card. */
export const historyPianoYears = historyYears

export function getHistoryPageIndexForYear(year: string) {
  const entry = historyYears.find((y) => y.year === year)
  if (!entry) return -1
  return Math.floor(entry.globalIndex / HISTORY_PAGE_SIZE)
}

export function getYearIndexOnPage(year: string) {
  const entry = historyYears.find((y) => y.year === year)
  if (!entry) return -1
  return entry.globalIndex % HISTORY_PAGE_SIZE
}

export function historyBookPageId(pageIndex: number) {
  return `p-history-${pageIndex}`
}

export interface HistoryPage {
  id: string
  index: number
  accent: 'purple' | 'blue'
  asideSide: 'left' | 'right'
  eyebrow: string
  quote: string
  body: string[]
  years: HistoryYearEntry[]
}

export const historyPages: HistoryPage[] = Array.from({ length: historyPageCount }, (_, index) => {
  const years = historyYears.slice(
    index * HISTORY_PAGE_SIZE,
    index * HISTORY_PAGE_SIZE + HISTORY_PAGE_SIZE,
  )
  const leadEra = historyEras[years[0]?.eraIndex ?? 0]
  return {
    id: `history-page-${index}`,
    index,
    accent: leadEra.accent,
    asideSide: leadEra.asideSide,
    eyebrow: leadEra.eyebrow,
    quote: leadEra.quote,
    body: leadEra.body,
    years,
  }
})

export function getHistoryPage(pageIndex: number) {
  return historyPages[Math.min(Math.max(pageIndex, 0), historyPageCount - 1)]
}
