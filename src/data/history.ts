export type HistoryYearEntry = HistoryYear & {
  eraId: string
  eraIndex: number
  globalIndex: number
}

export const historyYears: HistoryYearEntry[] = historyEras.flatMap((era, eraIndex) =>
  era.years.map((y, yearIndexInEra) => ({
    ...y,
    eraId: era.id,
    eraIndex,
    globalIndex:
      historyEras.slice(0, eraIndex).reduce((sum, e) => sum + e.years.length, 0) + yearIndexInEra,
  })),
)

/**
 * Five editorial periods for mobile + desktop history chapters.
 * Each range aligns with one history era intro (quote/body).
 */
export const HISTORY_CHAPTER_RANGES: ReadonlyArray<readonly string[]> = [
  ['2001', '2002', '2003', '2004', '2005', '2006', '2007', '2008', '2009', '2010'],
  ['2011', '2012', '2013', '2014', '2015', '2016'],
  ['2017', '2018', '2019', '2020'],
  ['2021', '2022', '2023', '2024'],
  ['2025', '2026'],
]

const yearById = new Map(historyYears.map((y) => [y.year, y]))

function resolveChapterYears(range: readonly string[]): HistoryYearEntry[] {
  return range.map((year) => {
    const entry = yearById.get(year)
    if (!entry) throw new Error(`Unknown history year in chapter: ${year}`)
    return entry
  })
}

function formatYearRange(years: HistoryYearEntry[]) {
  if (years.length === 1) return years[0].year
  return `${years[0].year}–${years[years.length - 1].year}`
}

export interface HistoryPage {
  id: string
  index: number
  accent: 'purple' | 'blue'
  asideSide: 'left' | 'right'
  eyebrow: string
  quote: string
  body: string[]
  years: HistoryYearEntry[]
  /** Display label for the chapter, e.g. «2001–2004» or «2019» */
  rangeLabel: string
  /** Multi-year editorial period vs single dense year page */
  chapterKind: 'period' | 'year'
}

export const historyPages: HistoryPage[] = HISTORY_CHAPTER_RANGES.map((range, index) => {
  const years = resolveChapterYears(range)
  const leadEra = historyEras[years[0]?.eraIndex ?? 0]
  return {
    id: `history-page-${index}`,
    index,
    accent: leadEra.accent,
    asideSide: 'left' as const,
    eyebrow: leadEra.eyebrow,
    quote: leadEra.quote,
    body: leadEra.body,
    years,
    rangeLabel: formatYearRange(years),
    chapterKind: years.length > 1 ? ('period' as const) : ('year' as const),
  }
})

export const historyPageCount = historyPages.length

/** Years shown in the side «piano» navigator — every year that has a timeline entry. */
export const historyPianoYears = historyYears

export function getHistoryPageIndexForYear(year: string) {
  return historyPages.findIndex((page) => page.years.some((y) => y.year === year))
}

export function getYearIndexOnPage(year: string) {
  const pageIndex = getHistoryPageIndexForYear(year)
  if (pageIndex < 0) return -1
  return historyPages[pageIndex].years.findIndex((y) => y.year === year)
}

export function historyBookPageId(pageIndex: number) {
  return `p-history-${pageIndex}`
}

export function getHistoryPage(pageIndex: number) {
  return historyPages[Math.min(Math.max(pageIndex, 0), historyPageCount - 1)]
}
